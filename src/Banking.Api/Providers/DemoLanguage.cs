    public static string Translate(string value) => Danish.GetValueOrDefault(value, value);
    public static string TranslateRule(string value) => value.Equals("transport", StringComparison.OrdinalIgnoreCase) ? "pendlerkort" : Translate(value);
    public static string? TranslateDetails(string? json)
    {
        if (json is null) return null;
        var node = System.Text.Json.Nodes.JsonNode.Parse(json);
        if (node is System.Text.Json.Nodes.JsonObject obj)
            foreach (var key in new[] { "Description", "Creditor", "Debtor", "BankDescription", "TransactionType", "Product" })
                if (obj[key] is System.Text.Json.Nodes.JsonValue value && value.TryGetValue<string>(out var text)) obj[key] = Translate(text);
        return node?.ToJsonString();
    }
