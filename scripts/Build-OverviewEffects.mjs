// Regenerate the two checked-in static assets from the pinned MIT source.
// Then bundle with: npm exec --yes --package=esbuild@0.25.12 -- esbuild prototypes/advisor/overview-effects/index.js --bundle --format=esm --target=es2022 --outfile=prototypes/advisor/public/overview-effects.js
import { readFile, writeFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
const base = new URL('../prototypes/advisor/', import.meta.url);
const source = await readFile(new URL('vendor/libraries-dev/border-beam/src/styles.ts', base), 'utf8');
const lib = await import('data:text/javascript;base64,' + Buffer.from(stripTypeScriptTypes(source)).toString('base64'));
const configs = {};
let css = '/* Border Beam by Jakub Antalik, MIT. Pinned source and license in ../vendor/libraries-dev. */\n';
for (const theme of ['dark', 'light']) {
 const id = `overview-ai-${theme}`, preset = lib.sizeThemePresets['pulse-inner'][theme];
 css += lib.generateBeamCSS({ ...preset, id, size: 'pulse-inner', theme, colorVariant: 'colorful', borderRadius: 18, borderWidth: 1,
  duration: 2.3, staticColors: false, brightness: preset.brightness ?? 1.3, saturation: preset.saturation, hueRange: 30, glowSize: 1 });
 configs[theme] = lib.getPulseDriverConfig('pulse-inner', theme, 2.3, 30, false, id);
}
css += await readFile(new URL('overview-effects/layout.css', base), 'utf8');
await writeFile(new URL('public/overview-effects.css', base), css);
await writeFile(new URL('overview-effects/pulse-config.js', base), '// Generated by scripts/Build-OverviewEffects.mjs\nexport const configs = ' + JSON.stringify(configs) + ';\n');
